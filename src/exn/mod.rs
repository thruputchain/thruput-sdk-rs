#[cfg(feature = "debugging")]
mod exn_impl {
    use crate::xdr::*;
    use core::error::Error;
    use core::fmt::Debug;

    pub trait Exn:
        Debug + PartialEq + Error + WriteXDR + ReadXDROwned
    {
    }

    impl<T> Exn for T where T: Debug + PartialEq + Error + WriteXDR + ReadXDROwned {}
}

#[cfg(not(feature = "debugging"))]
mod exn_impl {
    use crate::xdr::*;
    use core::fmt::Debug;

    pub trait Exn: Debug + PartialEq + WriteXDR + ReadXDROwned {}

    impl<T> Exn for T where T: Debug + PartialEq + WriteXDR + ReadXDROwned {}
}

/// Trait that maps a contract interface to its error type.
///
/// Generated by `#[contract]` on trait definitions. For a trait with
/// `#[contract(throws = MyError)]`, the macro generates:
///
/// ```ignore
/// impl ContractExn for dyn MyTrait {
///     type Exn = MyError;
/// }
/// ```
///
/// This allows the impl's export codegen to resolve the error type
/// without needing `throws` repeated on the impl.
pub trait ContractExn {
    type Exn: Exn;
}

